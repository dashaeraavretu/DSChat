#!/usr/bin/env node
/**
 * 为 Web 构建生成静态托管需要的文件：
 * - dist/_headers：Cloudflare Pages 安全响应头 + CSP（connect-src 跟随构建期 API origin）
 * - dist/sw.js：PWA 离线外壳（版本化缓存，导航 network-first，静态资源 cache-first）
 *
 * 在 rspack build 之后运行；只影响 Web 产物，不进入 Electron 安装包。
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dist = path.join(root, 'dist')
const indexPath = path.join(dist, 'index.html')

if (!existsSync(indexPath)) {
  console.error('[web] dist/index.html 不存在，请先运行 pnpm build')
  process.exit(1)
}

const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'))
let provider = { origin: 'https://api.deepseek.com' }
try {
  provider = JSON.parse(
    readFileSync(path.join(root, 'electron', 'provider-config.json'), 'utf8')
  )
} catch {
  // 使用官方默认值
}

const apiOrigin = (() => {
  try {
    return new URL(provider.origin).origin
  } catch {
    return 'https://api.deepseek.com'
  }
})()

const csp = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  `connect-src 'self' ${apiOrigin}`,
  "media-src 'self' data: blob:",
  "frame-src 'self' blob: data:",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
].join('; ')

const headers = `/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(self), geolocation=()

/sw.js
  Cache-Control: no-cache
  Content-Type: text/javascript; charset=utf-8
`

const version = String(pkg.version ?? '0').replace(/[^0-9A-Za-z._-]/g, '')
const serviceWorker = `/* Generated by scripts/write-web-deploy.mjs. Do not edit dist/sw.js directly. */
const CACHE = 'dschat-${version}'
const SHELL = [
  './',
  './index.html',
  './site.webmanifest',
  './favicon-32.png',
  './favicon-192.png',
  './favicon-512.png',
  './maskable-512.png',
]

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  if (url.pathname.endsWith('/sw.js')) return

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone()
          void caches.open(CACHE).then((cache) => cache.put('./index.html', copy))
          return response
        })
        .catch(async () => {
          return (
            (await caches.match('./index.html')) ||
            (await caches.match('./')) ||
            new Response('Offline', {
              status: 503,
              headers: { 'Content-Type': 'text/plain; charset=utf-8' },
            })
          )
        })
    )
    return
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((response) => {
          if (response.ok) {
            const copy = response.clone()
            void caches.open(CACHE).then((cache) => cache.put(request, copy))
          }
          return response
        })
        .catch(
          () =>
            cached ||
            new Response('Offline', {
              status: 503,
              headers: { 'Content-Type': 'text/plain; charset=utf-8' },
            })
        )
      return cached || network
    })
  )
})
`

writeFileSync(path.join(dist, '_headers'), headers)
writeFileSync(path.join(dist, 'sw.js'), serviceWorker)
console.log(`[web] wrote dist/_headers and dist/sw.js (api ${apiOrigin})`)
